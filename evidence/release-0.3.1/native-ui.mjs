// Final native smoke: split layout, paused cumulative readouts, mini commands and narrow drawer.
import assert from 'node:assert/strict';
import { cp, mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { createHash } from 'node:crypto';
import { parse, stringify } from 'yaml';
import { baseline, connect, count, kill, launch, loadEnv, sleep } from '../0.3.1-isolated/lib.mjs';

const env = await loadEnv(), out = resolve('evidence/release-0.3.1');
const stamp = Date.now(), backup = `${env.data}.before-ui-${stamp}`, lifecycle = join(env.profile, 'lifecycle.json');
const baselineInfo = b => ({ runHash: createHash('sha256').update(JSON.stringify(b.run)).digest('hex'), daily: b.daily });
const before = baselineInfo(baseline()), results = { before };
assert.ok(resolve(env.data).startsWith(resolve(tmpdir()) + '\\'));
assert.equal(count(env.exe), 0);
assert.equal(JSON.parse(await readFile(join(env.profile, 'config.json'), 'utf8')).root, env.data);
await mkdir(out, { recursive: true });
await rename(env.data, backup);
const savedLife = existsSync(lifecycle) ? `${lifecycle}.before-ui-${stamp}` : null;
if (savedLife) await rename(lifecycle, savedLife);
let main, mini;
const rows = async () => parse(await readFile(join(env.data, 'timelog', '2026-11-06.md'), 'utf8'));
try {
  await cp(join(tmpdir(), 'monorail-rt-data', 'a-031'), env.data, { recursive: true });
  const settingsFile = join(env.data, 'settings.yaml'), settings = parse(await readFile(settingsFile, 'utf8'));
  Object.assign(settings, { autostart: false, quickbarHotkey: 'Ctrl+Alt+Shift+F9', mainHotkey: 'Ctrl+Alt+Shift+F10',
    taskMode: true, homeLayout: 'split' });
  await writeFile(settingsFile, stringify(settings));
  launch(env.exe, 19412); main = await connect(19412, 'main');
  await main.waitFor("!!document.querySelector('.ins-top') && !!document.querySelector('.tbar')", 30_000, 'split insert');
  const titleTime = () => main.eval("document.querySelector('.status .st-time').textContent");
  const stripTime = () => main.eval("document.querySelector('#elapsed').textContent");
  assert.equal(await titleTime(), '15:00'); assert.equal(await stripTime(), '15:00');
  await sleep(1800); assert.equal(await titleTime(), '15:00'); assert.equal(await stripTime(), '15:00');
  await main.click('.dock-toggle[title="开关小窗口（M）"]'); mini = await connect(19412, 'mini');
  await mini.waitFor("!!document.querySelector('#mini-elapsed')");
  assert.equal(await mini.eval("document.querySelector('#mini-elapsed').textContent"), '15:00');
  await main.shot(join(out, 'ui-split-paused.png')); await mini.shot(join(out, 'ui-mini-paused.png'));
  await mini.click('[aria-label="继续"]');
  await main.waitFor("document.querySelector('.ins-top .readout').textContent.includes('插入中')");
  await sleep(2000);
  assert.notEqual(await titleTime(), '15:00');
  await mini.click('.mini-title'); await mini.waitFor("!!document.querySelector('#mini-name')");
  await mini.call('Input.dispatchKeyEvent', { type: 'keyDown', key: 'a', code: 'KeyA', modifiers: 2, windowsVirtualKeyCode: 65 });
  await mini.call('Input.dispatchKeyEvent', { type: 'keyUp', key: 'a', code: 'KeyA', modifiers: 2, windowsVirtualKeyCode: 65 });
  await mini.type('最终验收：回同事消息'); await mini.key('Enter');
  await main.waitFor("document.querySelector('.ins-top h1').textContent.includes('最终验收')");
  const renamed = (await rows()).filter(e => e.kind === '插入' && e.project !== '待机');
  assert.equal(renamed.length, 3); assert.ok(renamed.every(e => e.description === '最终验收：回同事消息'));
  await mini.click('[aria-label="暂停"]');
  await main.waitFor("document.querySelector('.status .st-label').textContent.includes('已暂停：最终验收')");
  const paused = await titleTime(); await sleep(1800); assert.equal(await titleTime(), paused);
  assert.equal(await stripTime(), paused);
  assert.equal(await mini.eval("document.querySelector('#mini-elapsed').textContent"), paused);
  results.readouts = { initial: '15:00', pausedAfterResume: paused, renamedSegments: renamed.length };
  await mini.click('[aria-label="回到任务"]');
  await main.waitFor("!document.querySelector('.ins-top')");
  await main.click('.dock-toggle.bp-bag');
  await main.waitFor("!!document.querySelector('.bp-drawer[data-open]')");
  await main.call('Emulation.setDeviceMetricsOverride', { width: 960, height: 600, deviceScaleFactor: 1, mobile: false });
  await sleep(500);
  const bounds = await main.eval("({ viewport:innerWidth, width:document.documentElement.scrollWidth, drawer:document.querySelector('.bp-drawer').getBoundingClientRect().right })");
  assert.ok(bounds.width <= bounds.viewport, JSON.stringify(bounds));
  await main.shot(join(out, 'ui-drawer-960.png'));
  await main.key('Escape'); await main.waitFor("!document.querySelector('.bp-drawer[data-open]')");
  results.viewport = bounds; results.escapeClosedDrawer = true;
  assert.equal(main.errors.length, 0, main.errors.join('\n')); assert.equal(mini.errors.length, 0, mini.errors.join('\n'));
  results.ok = true; console.log('PASS split/main/mini cumulative pause, rename, return, 960 drawer and Escape');
} finally {
  mini?.close(); main?.close(); kill(env.exe);
  if (existsSync(env.data)) await rename(env.data, `${env.data}.ui-result-${stamp}`);
  await rename(backup, env.data);
  if (existsSync(lifecycle)) await rename(lifecycle, `${lifecycle}.ui-result-${stamp}`);
  if (savedLife) await rename(savedLife, lifecycle);
  results.after = baselineInfo(baseline());
  await writeFile(join(out, 'native-ui.json'), JSON.stringify(results, null, 2));
}
assert.deepEqual(results.after, before);
